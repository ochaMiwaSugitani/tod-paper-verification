"""
時間間隔を考慮した頻出パターン抽出の本実装

医療指示を (経過日数, 医療指示種類) のタプルとしてエンコードし，
PrefixSpan-py ライブラリを用いて時間間隔を考慮した頻出パターンを抽出する．

論文：「頻出医療指示パターン中の経過日数・検査結果を考慮したバリアント抽出と
その可視化」（情報処理学会論文誌 TOD）の 4.3 節（実験環境）および
4.5.1 節（アルゴリズム実装の妥当性検証）で説明している本実装に対応する．
"""

from prefixspan import PrefixSpan


def extract_time_aware_patterns(sequences, minsup, closed=True):
    """
    時間間隔を考慮した頻出パターンを抽出する．

    本関数は，各医療指示を (経過日数, 医療指示種類) のタプルとしてエンコードした
    シーケンスを入力として受け取り，PrefixSpan-py の PrefixSpan アルゴリズムを
    そのまま適用することで，経過日数の違いを区別しながら頻出パターンを抽出する．

    例えば，(1, '抗生剤') と (2, '抗生剤') は，同じ「抗生剤」というアイテムでも
    経過日数が異なるため，異なるアイテムとして扱われる．これにより，時間間隔
    （経過日数の組み合わせ）を保持した頻出パターン抽出が実現される．

    Parameters
    ----------
    sequences : list of list of tuple
        各シーケンスは (経過日数, 医療指示種類) のタプルのリスト．
        例：[[(0, '手術'), (1, '抗生剤')], [(0, '手術'), (2, '抗生剤')], ...]
    minsup : int
        最小支持度（出現シーケンス数の絶対値）．
        例：minsup=3 は，3 シーケンス以上に出現するパターンを「頻出」と判定する．
    closed : bool, default True
        True のとき，クローズド頻出パターンのみを返す．
        False のとき，すべての頻出パターンを返す．

    Returns
    -------
    list of (int, list of tuple)
        (サポート値, パターン) のリスト．
        サポート値はそのパターンが出現したシーケンス数，
        パターンは (経過日数, 医療指示種類) のタプルのリスト．
    """
    ps = PrefixSpan(sequences)
    patterns = ps.frequent(minsup, closed=closed)
    return patterns
